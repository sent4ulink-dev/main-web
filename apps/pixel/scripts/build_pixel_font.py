order=font.getGlyphOrder()
for char, pattern in (upper | lower).items():
    rows=pattern.split('/'); name=f'uni{ord(char):04X}'; pen=TTGlyphPen(None)
    top=400 if char in 'руүф' else len(rows)*80
    for y,row in enumerate(rows):
        for x,bit in enumerate(row):
            if bit=='1':
                left=40+x*64; bottom=top-(y+1)*80
                pen.moveTo((left,bottom)); pen.lineTo((left,bottom+80))
                pen.lineTo((left+64,bottom+80)); pen.lineTo((left+64,bottom)); pen.closePath()
    font['glyf'][name]=pen.glyph(); font['hmtx'][name]=(400,40)
    if name not in order: order.append(name)
    for table in font['cmap'].tables:
        if table.isUnicode(): table.cmap[ord(char)]=name
font.setGlyphOrder(order)
for record in font['name'].names:
    if record.nameID in (1,3,4,6):
        value='LoveLCD-Regular' if record.nameID in (3,6) else 'Love LCD'
        record.string=value.encode(record.getEncoding())
font['OS/2'].ulUnicodeRange1 |= 1 << 9
